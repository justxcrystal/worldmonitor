import { seedProfile, waitForBoot } from './_profile.mjs';
import assert from 'node:assert/strict';
export default async function ({ page, base, shot, log, expectVisible }) {
  await seedProfile(page, { localStorage: { 'wm-pro-key': 'verification', 'worldmonitor-panels': JSON.stringify({ 'home-satellites': { name: 'Satellites at Home', enabled: true, priority: 1 } }) } });
  const now = new Date();
  const year = now.getUTCFullYear();
  const day = (now - Date.UTC(year, 0, 1)) / 86400000 + 1;
  const epoch = `${String(year).slice(2)}${day.toFixed(8).padStart(12, '0')}`;
  const tle = `ISS TEST FIXTURE\n1 25544U 98067A   ${epoch}  .00003075  00000-0  59442-4 0  9992\n2 25544  51.6433  59.2583 0008217  16.4489 347.6017 15.51174618173442`;
  const checkedTle = tle.split('\n').map(line => /^[12] /.test(line) ? line.slice(0, 68) + ([...line.slice(0, 68)].reduce((sum, c) => sum + (/\d/.test(c) ? Number(c) : c === '-' ? 1 : 0), 0) % 10) : line).join('\n');
  await page.route('https://celestrak.org/**', route => route.fulfill({ status: 200, contentType: 'text/plain', body: checkedTle }));
  await page.goto(`${base}/dashboard`, { waitUntil: 'domcontentloaded' });
  await waitForBoot(page);
  const panel = page.locator('[data-panel="home-satellites"]');
  await panel.scrollIntoViewIfNeeded();
  await expectVisible('[data-panel="home-satellites"] .home-satellite-form');
  await shot('before-location');
  await panel.locator('[name="latitude"]').fill('29.65');
  await panel.locator('[name="longitude"]').fill('-81.64');
  await panel.locator('button[type="submit"]').click();
  await page.waitForFunction(() => document.querySelector('.home-satellite-status')?.textContent.includes('1 usable objects'));
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('wm-home-satellite-observer')).longitude), -81.64);
  assert.ok((await panel.locator('.home-satellite-results').innerText()).includes('ISS TEST FIXTURE'));
  await shot('predictions-desktop-controlled-tle');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await waitForBoot(page);
  await panel.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('.home-satellite-status')?.textContent.includes('1 usable objects'));
  assert.equal(await panel.locator('[name="latitude"]').inputValue(), '29.65');
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.scrollIntoViewIfNeeded();
  await shot('predictions-mobile-controlled-tle');
  await page.unroute('https://celestrak.org/**');
  await page.route('https://celestrak.org/**', route => route.fulfill({ status: 503, body: 'Unavailable' }));
  await panel.locator('[data-action="refresh"]').click();
  await page.waitForFunction(() => document.querySelector('.home-satellite-status')?.textContent.includes('Public feed unavailable'));
  await shot('feed-error');
  await panel.locator('.home-tle-file').setInputFiles({ name: 'test.tle', mimeType: 'text/plain', buffer: Buffer.from(checkedTle) });
  await page.waitForFunction(() => document.querySelector('.home-satellite-status')?.textContent.includes('Imported TLE file'));
  await panel.locator('[data-action="clear"]').click();
  assert.equal(await page.evaluate(() => localStorage.getItem('wm-home-satellite-observer')), null);
  assert.equal(await panel.locator('.home-satellite-results').innerText(), '');
  log('proof', 'location save/reload/clear, controlled TLE predictions, import, feed error, desktop/mobile; live public feed not verified');
}
